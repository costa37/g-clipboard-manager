import AppKit

/// Reads a single clipboard generation; Store commits it only if changeCount stayed stable.
enum ClipboardIO {
    enum ReadResult { case retry, skip(String?), clip(Clip) }
    static let limit = 10 * 1024 * 1024
    static let excluded = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])

    static func read(_ board: NSPasteboard, source: String) -> ReadResult {
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: excluded) else { return .skip(nil) }
        var data: [String: Data] = [:]
        // Retain one image representation, not redundant PNG + uncompressed TIFF.
        if types.contains(NSPasteboard.PasteboardType.png.rawValue),
           let png = board.data(forType: .png), !png.isEmpty, png.count <= limit {
            data[NSPasteboard.PasteboardType.png.rawValue] = png
        } else if let tiff = board.data(forType: .tiff), !tiff.isEmpty {
            if tiff.count <= limit { data[NSPasteboard.PasteboardType.tiff.rawValue] = tiff }
            else if let bitmap = NSBitmapImageRep(data: tiff),
                    let png = bitmap.representation(using: .png, properties: [:]), png.count <= limit {
                data[NSPasteboard.PasteboardType.png.rawValue] = png
            } else { return .skip("Skipped an image larger than 10 MB after compression.") }
        } else if let png = board.data(forType: .png), png.count > limit {
            return .skip("Skipped an image larger than 10 MB.")
        }
        // Some apps publish only an encoded image, without PNG or TIFF.
        if data.isEmpty {
            for name in ["public.jpeg", "public.heic", "com.compuserve.gif", "com.microsoft.bmp"] where types.contains(name) {
                guard let bytes = board.data(forType: .init(name)), !bytes.isEmpty else { return .retry }
                guard let bitmap = NSBitmapImageRep(data: bytes), let png = bitmap.representation(using: .png, properties: [:]) else {
                    return .skip("Could not decode the copied image.")
                }
                guard png.count <= limit else { return .skip("Skipped an image larger than 10 MB after conversion.") }
                data[NSPasteboard.PasteboardType.png.rawValue] = png
                break
            }
        }
        if !data.isEmpty { return .clip(Clip(text: "", source: source, data: data)) }
        if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            return .retry // Do not record an image's text fallback while image data is pending.
        }
        for type: NSPasteboard.PasteboardType in [.string, .rtf, .html] {
            if let bytes = board.data(forType: type), !bytes.isEmpty { data[type.rawValue] = bytes }
        }
        if data[NSPasteboard.PasteboardType.string.rawValue] == nil,
           let url = board.string(forType: .URL), !url.isEmpty {
            data[NSPasteboard.PasteboardType.string.rawValue] = Data(url.utf8)
        }
        guard !data.isEmpty else { return .retry }
        guard data.values.reduce(0, { $0 + $1.count }) <= limit else { return .skip("Skipped a text clip larger than 10 MB.") }
        var clip = Clip(text: board.string(forType: .string) ?? board.string(forType: .URL) ?? "", source: source, data: data)
        if clip.text.isEmpty { clip.text = clip.attributed.string }
        guard !clip.text.isEmpty else { return .retry }
        return .clip(clip)
    }

    static func write(_ clip: Clip, rich: Bool, to board: NSPasteboard) -> Bool {
        // Stage representations together instead of issuing unchecked individual writes.
        let item = NSPasteboardItem()
        if clip.isImage || rich {
            for (key, data) in clip.data {
                guard item.setData(data, forType: .init(key)) else { return false }
            }
        }
        if !clip.isImage { guard item.setString(clip.text, forType: .string) else { return false } }
        guard !item.types.isEmpty else { return false }
        board.clearContents()
        return board.writeObjects([item])
    }
}
